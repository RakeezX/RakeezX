import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = resolve(ROOT, 'src/generated/build-meta.generated.js');
const INPUT_ROOTS = ['assets', 'src'];
const INPUT_FILES = ['index.html', 'manifest.webmanifest', 'package.json', 'sw.js'];
const OUTPUT_RELATIVE = relative(ROOT, OUTPUT).replaceAll('\\', '/');

async function filesUnder(directory) {
  const entries = await readdir(resolve(ROOT, directory), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const child = `${directory}/${entry.name}`;
    if (entry.isDirectory()) files.push(...await filesUnder(child));
    else if (entry.isFile() && child !== OUTPUT_RELATIVE) files.push(child);
  }
  return files;
}

export async function computeBuildFingerprint() {
  const paths = [...INPUT_FILES];
  for (const root of INPUT_ROOTS) paths.push(...await filesUnder(root));
  paths.sort();
  const hash = createHash('sha256');
  for (const path of paths) {
    hash.update(`${path}\0`);
    hash.update(await readFile(resolve(ROOT, path)));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function safeGitSha(value) {
  const sha = String(value ?? '').trim().toLowerCase();
  return /^[a-f0-9]{40}$/.test(sha) ? sha : null;
}

function buildTimestamp() {
  const explicit = String(process.env.CF_PAGES_BUILD_TIME ?? '').trim();
  if (explicit && Number.isFinite(Date.parse(explicit))) return new Date(explicit).toISOString();
  const epoch = Number(process.env.SOURCE_DATE_EPOCH);
  if (Number.isFinite(epoch) && epoch > 0) return new Date(epoch * 1000).toISOString();
  return new Date().toISOString();
}

export async function createGeneratedBuildMeta() {
  const packageJson = JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8'));
  const gitSha = safeGitSha(process.env.CF_PAGES_COMMIT_SHA ?? process.env.GITHUB_SHA);
  return {
    appVersion: packageJson.version,
    buildSha: gitSha ?? await computeBuildFingerprint(),
    buildShaKind: gitSha ? 'git' : 'content',
    buildTimestamp: buildTimestamp(),
    canonicalOrigin: 'https://rakeezx.com',
  };
}

export async function writeGeneratedBuildMeta() {
  const meta = await createGeneratedBuildMeta();
  const source = `/** Generated by scripts/generate-build-meta.mjs. Do not edit manually. */\nexport const GENERATED_BUILD_META = Object.freeze(${JSON.stringify(meta, null, 2)});\n`;
  await writeFile(OUTPUT, source, 'utf8');
  return meta;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const meta = await writeGeneratedBuildMeta();
  console.log(`Build Meta ${meta.appVersion} ${meta.buildSha.slice(0, 12)} (${meta.buildShaKind})`);
}
