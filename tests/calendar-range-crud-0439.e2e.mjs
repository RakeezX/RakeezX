import { test, expect } from '@playwright/test';

test('custom Calendar range edits, moves, deletes and recreates through the real controls', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/#/calendar');
  await page.getByRole('button', { name: 'إضافة استثناء' }).click();
  let form = page.getByRole('dialog').locator('#range-form');
  await form.locator('[name="holidayReference"]').selectOption('other');
  await form.getByLabel('من *').fill('2026-10-05');
  await form.getByLabel('إلى').fill('2026-10-07');
  await form.getByLabel('الوصف أو اسم الفترة *').fill('اختبار 0439');
  await page.getByRole('dialog').getByRole('button', { name: 'إضافة الاستثناء' }).click();
  let row = page.locator('.holiday-row').filter({ hasText: 'اختبار 0439' });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'تفاصيل اختبار 0439' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'تعديل الاستثناء' }).click();
  form = page.getByRole('dialog').locator('#range-form');
  await form.getByLabel('إلى').fill('2026-10-06');
  await form.getByLabel('الوصف أو اسم الفترة *').fill('اختبار 0439 معدّل');
  await page.getByRole('dialog').getByRole('button', { name: 'حفظ التعديل' }).click();
  await expect(page.locator('.holiday-row').filter({ hasText: 'اختبار 0439 معدّل' })).toHaveCount(1);
  await page.reload();
  row = page.locator('.holiday-row').filter({ hasText: 'اختبار 0439 معدّل' });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'تفاصيل اختبار 0439 معدّل' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'تعديل الاستثناء' }).click();
  form = page.getByRole('dialog').locator('#range-form');
  await form.getByLabel('من *').fill('2026-10-08');
  await form.getByLabel('إلى').fill('2026-10-09');
  await page.getByRole('dialog').getByRole('button', { name: 'حفظ التعديل' }).click();
  row = page.locator('.holiday-row').filter({ hasText: 'اختبار 0439 معدّل' });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'تفاصيل اختبار 0439 معدّل' }).click();
  await expect(page.getByRole('dialog')).toContainText('8 – 9 أكتوبر 2026');
  await page.getByRole('dialog').getByRole('button', { name: 'حذف الاستثناء' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'حذف الاستثناء' }).click();
  await expect(page.locator('.holiday-row').filter({ hasText: 'اختبار 0439 معدّل' })).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: 'إضافة استثناء' }).click();
  form = page.getByRole('dialog').locator('#range-form');
  await form.locator('[name="holidayReference"]').selectOption('other');
  await form.getByLabel('من *').fill('2026-10-08');
  await form.getByLabel('إلى').fill('2026-10-08');
  await form.getByLabel('الوصف أو اسم الفترة *').fill('إعادة إنشاء 0439');
  await page.getByRole('dialog').getByRole('button', { name: 'إضافة الاستثناء' }).click();
  await expect(page.locator('.holiday-row').filter({ hasText: 'إعادة إنشاء 0439' })).toHaveCount(1);
  expect(errors).toEqual([]);
});
